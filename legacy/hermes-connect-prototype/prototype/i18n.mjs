function detectBrowserLocale() {
  const preferred = (navigator.languages || [navigator.language || "en"]).map((l) => l.slice(0, 2).toLowerCase());
  return preferred.find((code) => LOCALE_CODES.has(code)) || null;
}

export function getLocale() {
  const fromQuery = new URLSearchParams(window.location.search).get("lang");
  if (fromQuery && LOCALE_CODES.has(fromQuery)) return fromQuery;
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored && LOCALE_CODES.has(stored)) return stored;
  return detectBrowserLocale() || "en";
}

export function setLocale(code) {
  if (!LOCALE_CODES.has(code)) return;
  window.localStorage.setItem(STORAGE_KEY, code);
  const url = new URL(window.location.href);
  url.searchParams.set("lang", code);
  window.history.replaceState({}, "", url);
}

let currentLocale = getLocale();

export function t(key, vars) {
  const table = dict[currentLocale] || dict.en;
  let value = table[key] ?? dict.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, val]) => {
      value = value.replaceAll(`{${name}}`, val);
    });
  }
  return value;
}

export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
}

export function renderLanguageSwitcher(container, onChange) {
  const select = document.createElement("select");
  select.className = "lang-switcher";
  select.setAttribute("aria-label", "Language");
  locales.forEach(({ code, name }) => {
    const option = document.createElement("option");
    option.value = code;
    option.textContent = name;
    if (code === currentLocale) option.selected = true;
    select.append(option);
  });
  select.addEventListener("change", () => {
    currentLocale = select.value;
    setLocale(select.value);
    applyTranslations();
    onChange?.(select.value);
  });
  container.append(select);
  return select;
}
