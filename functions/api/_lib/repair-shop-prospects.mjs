export async function ensureRepairShopProspectSchema(db) {
  await db.prepare(`
    CREATE TABLE IF NOT EXISTS repair_shop_prospects (
      id TEXT PRIMARY KEY,
      source_system TEXT NOT NULL,
      source_ref TEXT NOT NULL UNIQUE,
      business_name TEXT NOT NULL,
      shop_type TEXT,
      state TEXT,
      city TEXT,
      address_line1 TEXT,
      phone TEXT,
      email TEXT,
      website TEXT,
      social_url TEXT,
      contact_name TEXT,
      contact_role TEXT,
      services_summary TEXT,
      website_observation TEXT,
      social_observation TEXT,
      crm_stage TEXT,
      crm_call_result TEXT,
      crm_decision_maker_reached TEXT,
      crm_interest_level TEXT,
      crm_budget_range TEXT,
      profile_state TEXT NOT NULL DEFAULT 'prefilled',
      claim_state TEXT NOT NULL DEFAULT 'unclaimed',
      public_profile_enabled INTEGER NOT NULL DEFAULT 0,
      claimed_shop_id TEXT,
      claimed_owner_specialist_id TEXT,
      claimed_at TEXT,
      provenance_json TEXT,
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL
    )
  `).run();
  await db.prepare("CREATE UNIQUE INDEX IF NOT EXISTS idx_repair_shop_prospects_source_ref ON repair_shop_prospects(source_ref)").run();
  await db.prepare("CREATE INDEX IF NOT EXISTS idx_repair_shop_prospects_claim_state ON repair_shop_prospects(claim_state, updated_at DESC)").run();
}

