import assert from "node:assert/strict";
import fs from "node:fs";
const read = (p) => fs.readFileSync(new URL("../" + p, import.meta.url), "utf8");
const crypto = read("functions/api/_lib/apple-oidc.mjs");
const state = read("functions/api/_lib/federated-login.mjs");
const start = read("functions/api/auth/apple/start.ts");
const callback = read("functions/api/auth/apple/callback.ts");

assert.match(crypto, /APPLE_LOGIN_ENABLED === "true"/);
assert.match(crypto, /APPLE_SERVICES_ID/);
assert.match(crypto, /APPLE_REDIRECT_URI/);
assert.match(crypto, /appleid\.apple\.com\/auth\/keys/);
assert.match(crypto, /jwt\.header\.alg !== "RS256"/);
assert.match(crypto, /RSASSA-PKCS1-v1_5/);
assert.match(crypto, /claims\.nonce !== nonce/);
assert.match(crypto, /claims\.aud !== servicesId/);
assert.match(crypto, /claims\.iss !== "https:\/\/appleid\.apple\.com"/);
assert.match(crypto, /claims\.email_verified/);
assert.match(crypto, /ECDSA/);
assert.match(crypto, /exp: now \+ 300/);
assert.match(start, /response_mode", "form_post"/);
assert.match(start, /response_type", "code"/);
assert.match(start, /secureStateCookie\("apple", state, \{ crossSitePost: true \}\)/);
assert.match(callback, /consumeOAuthState\(env.DB, request, "apple", state\)/);
assert.match(callback, /https:\/\/appleid\.apple\.com\/auth\/token/);
assert.match(callback, /verifyAppleIdentityToken/);
assert.match(callback, /completeFederatedLogin/);
assert.match(state, /used_at IS NULL AND expires_at >/);
assert.match(state, /existing_account_signin_required/);
console.log("hermes-apple-auth-contract: disabled default, CSRF nonce, one-shot code, OIDC signature/claim verification and shared Hermes identity PASS");
