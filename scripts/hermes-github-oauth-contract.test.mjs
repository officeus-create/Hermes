import assert from "node:assert/strict";
import fs from "node:fs";
const read = (path) => fs.readFileSync(new URL("../" + path, import.meta.url), "utf8");
const state = read("functions/api/_lib/federated-login.mjs");
const start = read("functions/api/auth/github/start.ts");
const callback = read("functions/api/auth/github/callback.ts");

assert.match(start, /GITHUB_LOGIN_ENABLED === "true"/);
assert.match(start, /GITHUB_OAUTH_REDIRECT_URI/);
assert.match(start, /\/api\/auth\/github\/callback/);
assert.match(start, /scope", "user:email"/);
assert.match(start, /code_challenge_method", "S256"/);
assert.match(start, /secureStateCookie\("github"/);
assert.match(callback, /\/login\/oauth\/access_token/);
assert.match(callback, /code_verifier: String\(context\.code_verifier\)/);
assert.match(callback, /\/user\/emails\?per_page=100/);
assert.match(callback, /e\.verified && e\.primary/);
assert.match(callback, /Number\.isSafeInteger\(profile\.id\)/);
assert.match(callback, /completeFederatedLogin/);
assert.match(callback, /provider: "github"/);
assert.doesNotMatch(callback, /scope.*repo(?!rt)/i);
assert.match(state, /__Host-hermes_/);
assert.match(state, /SameSite=Lax/);
assert.match(state, /STATE_TTL_MS = 10 \* 60_000/);
assert.match(state, /used_at IS NULL AND expires_at >/);
assert.match(state, /consumed\?\.meta\?\.changes/);
assert.match(state, /existing_account_signin_required/);
assert.match(state, /getAuthenticatedSpecialist\(request, db\)/);
assert.match(state, /ON CONFLICT\(provider,provider_subject\) DO NOTHING/);
assert.match(state, /persisted\.specialist_id !== specialist\.id/);
assert.doesNotMatch(state, /DO UPDATE SET\s+specialist_id/i);
console.log("hermes-github-oauth-contract: configured-only provider, PKCE, one-time state, verified GitHub email, canonical owner-scoped identity PASS");
